export function costTier(costIndex: number): { label: string; symbol: string } {
  if (costIndex < 0.8) return { label: "Affordable", symbol: "$" };
  if (costIndex <= 1.2) return { label: "Moderate", symbol: "$$" };
  return { label: "Premium", symbol: "$$$" };
}

